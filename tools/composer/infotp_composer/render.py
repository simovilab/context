"""Emitters: turn a ComposedNode into JSON and Markdown."""

from __future__ import annotations

from typing import Any, Dict

from .compose import ComposedNode


def to_json(composed: ComposedNode) -> Dict[str, Any]:
    """Fully deterministic JSON representation: a pure function of the source
    tree, so regenerating without source changes yields byte-identical output
    (no volatile timestamp) — keeps the git-first .composed/ store diff-clean."""
    return {
        "id": composed.id,
        "name": composed.name,
        "component": composed.component,
        "kind": list(composed.kind),
        "status": composed.status,
        "owner": list(composed.owner),
        "result": composed.result,
        "depends_on": list(composed.depends_on),
        "hito": composed.hito,
        "due_month": composed.due_month,
        "chain": list(composed.chain),
        "directives": [
            {
                "key": d.key,
                "text": d.text,
                "applies_to": list(d.applies_to),
                "lang": d.lang,
                "sources": list(d.sources),
            }
            for d in composed.directives
        ],
        "reference": [
            {"file": r.file, "source": r.source, "path": r.path} for r in composed.reference
        ],
        "token_estimate": dict(composed.token_estimate),
    }


def _metadata_line(composed: ComposedNode) -> str:
    parts = []
    if composed.component:
        parts.append(composed.component)
    parts.append(composed.status)
    if composed.owner:
        parts.append(", ".join(composed.owner))
    hito_month = None
    if composed.hito and composed.due_month:
        hito_month = f"Hito {composed.hito} / month {composed.due_month}"
    elif composed.hito:
        hito_month = f"Hito {composed.hito}"
    elif composed.due_month:
        hito_month = f"month {composed.due_month}"
    if hito_month:
        parts.append(hito_month)
    if composed.result:
        parts.append(f"{composed.result.get('type')} ({composed.result.get('visibility')})")
    return " · ".join(parts)


def to_markdown(composed: ComposedNode) -> str:
    lines = []
    lines.append(f"# `{composed.name}` (`{composed.id}`)")
    lines.append("")
    lines.append(_metadata_line(composed))
    lines.append("")
    lines.append("## Directives (composed)")
    lines.append("")
    if not composed.directives:
        lines.append("None yet.")
    else:
        for d in composed.directives:
            lines.append(f"### {d.key}")
            lines.append("")
            lines.append(d.text)
            lines.append("")
            provenance = " → ".join(d.sources)
            lines.append(f"_from: {provenance}_")
            lines.append("")
    lines.append("## Reference corpus")
    lines.append("")
    if not composed.reference:
        lines.append("None yet.")
    else:
        for r in composed.reference:
            lines.append(f"- `{r.path}` (from {r.source})")
    lines.append("")
    method = composed.token_estimate.get("method")
    tokens = composed.token_estimate.get("directives")
    ref_tokens = composed.token_estimate.get("reference")
    lines.append(
        "Generated by the InfoTP composer — do not hand-edit (D4). "
        f"Token estimate: {tokens} directives + {ref_tokens} reference "
        f"(fetched via RAG) = {composed.token_estimate.get('total')} total ({method})."
    )
    return "\n".join(lines) + "\n"
